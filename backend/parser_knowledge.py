def build_knowledge_prompt(customer_registry: list[dict]) -> str:
    """Builds the full system prompt body for the parser.

    Mirrors legacy buildKnowledgePrompt(customerCache). Combines:
      - EMBEDDED_KNOWLEDGE constants (always present)
      - Customer registry (cust_code | cust_name lines)
    """
    parts = [
        SYSTEM_PROMPT_HEADER,
        "═════════ EMBEDDED KNOWLEDGE FALLBACK (D-136, R1.6.3) ═════════",
        "",
        EMBEDDED_KNOWLEDGE,
        "",
    ]
    if customer_registry:
        parts.append(
            f"═════════ SPC CUSTOMER REGISTRY ({len(customer_registry)} entries — "
            "emit cust_code directly when matched) ═════════"
        )
        parts.append("Format: <cust_code> | <cust_name>")
        parts.append("")
        for c in customer_registry:
            code = (c.get("code") or "").strip()
            name = (c.get("name") or "").strip()
            if code and name:
                parts.append(f"{code} | {name}")
        parts.append("")
    return "\n".join(parts)
